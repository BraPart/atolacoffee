(() => {
  const $ = (s, c = document) => c.querySelector(s);
  const root = document.documentElement;

  // Dark mode (remembers choice, falls back to system preference)
  const themeBtn = $('#theme');
  let saved = null;
  try { saved = localStorage.getItem('atole-theme'); } catch (e) {}
  const prefersDark = matchMedia('(prefers-color-scheme: dark)').matches;
  const setTheme = t => {
    root.dataset.theme = t;
    themeBtn.textContent = t === 'dark' ? '☀' : '☾';
  };
  setTheme(saved || (prefersDark ? 'dark' : 'light'));
  themeBtn.addEventListener('click', () => {
    const next = root.dataset.theme === 'dark' ? 'light' : 'dark';
    setTheme(next);
    try { localStorage.setItem('atole-theme', next); } catch (e) {}
  });

  // Mobile menu
  const menu = $('#menu'), burger = $('#burger');
  const toggle = open => {
    menu.classList.toggle('open', open);
    burger.setAttribute('aria-expanded', open);
    burger.textContent = open ? '×' : '☰';
  };
  burger.addEventListener('click', () => toggle(!menu.classList.contains('open')));
  menu.addEventListener('click', e => { if (e.target.tagName === 'A') toggle(false); });

  // Sticky nav background + floating order button
  const nav = $('#nav'), fo = $('#floatOrder'), hero = $('#home'), order = $('#order');
  let orderVisible = false;
  new IntersectionObserver(([e]) => { orderVisible = e.isIntersecting; update(); }).observe(order);
  const update = () => {
    const y = scrollY;
    nav.classList.toggle('solid', y > 40);
    fo.classList.toggle('show', y > hero.offsetHeight * 0.6 && !orderVisible);
  };
  addEventListener('scroll', update, { passive: true });
  update();

  // Scroll reveal (about + a few key blocks only)
  const io = new IntersectionObserver(es => es.forEach(e => {
    if (e.isIntersecting) { e.target.classList.add('in'); io.unobserve(e.target); }
  }), { threshold: 0.15 });
  document.querySelectorAll('.reveal').forEach(el => io.observe(el));

  // Gallery lightbox
  const lb = $('#lb'), lbImg = $('#lbImg'), lbCap = $('#lbCap');
  document.querySelectorAll('.g').forEach(g => g.addEventListener('click', () => {
    lbImg.style.backgroundImage = getComputedStyle(g).backgroundImage;
    lbCap.textContent = lang === 'ar' ? CAPS[g.dataset.cap] : g.dataset.cap;
    lb.hidden = false;
  }));
  const close = () => { lb.hidden = true; };
  lb.addEventListener('click', close);
  addEventListener('keydown', e => { if (e.key === 'Escape') { close(); toggle(false); } });


  // Customer photos on reviews: shown only when the image file exists
  const exts = ['jpg', 'jpeg', 'png', 'webp'];
  document.querySelectorAll('.rev-photo').forEach(el => {
    let i = 0;
    const next = () => {
      if (i >= exts.length) return;
      const src = 'images/' + el.dataset.photo + '.' + exts[i++];
      const im = new Image();
      im.onload = () => { el.style.backgroundImage = 'url(' + src + ')'; el.classList.add('show'); };
      im.onerror = next;
      im.src = src;
    };
    next();
    el.addEventListener('click', () => {
      lbImg.style.backgroundImage = el.style.backgroundImage;
      lbCap.textContent = el.dataset.name;
      lb.hidden = false;
    });
  });

  // Scrollable reviews: arrows, swipe and mouse drag
  const track = $('#revTrack');
  if (track) {
    const go = d => {
      const card = track.querySelector('.rev');
      const step = (card ? card.offsetWidth : 320) + 16;
      track.scrollBy({ left: d * step * (root.dir === 'rtl' ? -1 : 1), behavior: 'smooth' });
    };
    $('#rvPrev').addEventListener('click', () => go(-1));
    $('#rvNext').addEventListener('click', () => go(1));
    let down = false, moved = false, sx = 0, sl = 0;
    track.addEventListener('pointerdown', e => {
      if (e.pointerType !== 'mouse') return;
      down = true; moved = false; sx = e.clientX; sl = track.scrollLeft;
      track.style.scrollSnapType = 'none'; track.classList.add('drag');
    });
    addEventListener('pointermove', e => {
      if (!down) return;
      const dx = e.clientX - sx;
      if (Math.abs(dx) > 4) moved = true;
      track.scrollLeft = sl - dx;
    });
    addEventListener('pointerup', () => {
      if (!down) return;
      down = false; track.style.scrollSnapType = ''; track.classList.remove('drag');
    });
    track.addEventListener('click', e => { if (moved) { e.stopPropagation(); e.preventDefault(); moved = false; } }, true);
  }

  // Language switch (English / Arabic, RTL)
  const langBtn = $('#lang');
  const nodes = [...document.querySelectorAll('[data-i18n]')];
  nodes.forEach(n => n.dataset.en = n.innerHTML);
  let lang = 'en';
  const setLang = l => {
    lang = l;
    root.lang = l; root.dir = l === 'ar' ? 'rtl' : 'ltr';
    nodes.forEach(n => { n.innerHTML = l === 'ar' ? AR[n.dataset.i18n] : n.dataset.en; });
    langBtn.textContent = l === 'ar' ? 'EN' : 'ع';
    document.title = l === 'ar' ? 'أتول كافيه | قهوة وشاي كرك في المنصورة، الرياض' : 'Atole Cafe | Karak Tea & Premium Coffee in Al Mansourah, Riyadh';
    $('#yr').textContent = new Date().getFullYear();
    try { localStorage.setItem('atole-lang', l); } catch (e) {}
  };
  langBtn.addEventListener('click', () => setLang(lang === 'ar' ? 'en' : 'ar'));
  let savedLang = null;
  try { savedLang = localStorage.getItem('atole-lang'); } catch (e) {}
  if (savedLang === 'ar') setLang('ar');
  $('#yr').textContent = new Date().getFullYear();
})();
